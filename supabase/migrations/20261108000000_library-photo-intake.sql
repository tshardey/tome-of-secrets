-- True when the object's first folder segment is a household of the caller.
-- Compared as text, so a non-UUID segment is simply false.
create or replace function library.can_access_intake_object(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from library.household_members m
     where m.user_id = auth.uid()
       and m.household_id::text = (storage.foldername(p_name))[1]
  );
$$;

