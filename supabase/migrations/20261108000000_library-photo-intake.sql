create or replace function library.claim_intake_item(p_item uuid)
returns table (outcome text, claim_token uuid, attempts int, cover_path text,
               title_page_path text, retry_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_item  library.intake_items%rowtype;
  v_calls int;
  v_token uuid;
begin
  select i.* into v_item from library.intake_items i where i.id = p_item for update;
  if not found or not library.is_member(v_item.household_id) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  if v_item.status in ('ready', 'confirmed', 'discarded', 'failed') then
    return query select 'done'::text, null::uuid, v_item.attempts, null::text, null::text, null::timestamptz;
    return;
  end if;

  if v_item.status = 'processing' and v_item.claimed_at > now() - interval '7 minutes' then
    return query select 'busy'::text, null::uuid, v_item.attempts, null::text, null::text, null::timestamptz;
    return;
  end if;

  if v_item.status = 'pending' and v_item.retry_at > now() then
    return query select 'retry_later'::text, null::uuid, v_item.attempts, null::text, null::text, v_item.retry_at;
    return;
  end if;

  -- Due: pending, or processing with an expired lease.
  if v_item.attempts >= 3 then
    update library.intake_items i
       set status = 'failed', error_code = 'attempts_exhausted', claim_token = null, retry_at = null
     where i.id = p_item;
    return query select 'failed'::text, null::uuid, v_item.attempts, null::text, null::text, null::timestamptz;
    return;
  end if;

  insert into library.intake_usage as u (household_id, day, vision_calls)
  values (v_item.household_id, (now() at time zone 'utc')::date, 1)
  on conflict (household_id, day) do update
    set vision_calls = u.vision_calls + 1
    where u.vision_calls < 500
  returning u.vision_calls into v_calls;

  if v_calls is null then
    return query select 'daily_cap'::text, null::uuid, v_item.attempts, null::text, null::text, null::timestamptz;
    return;
  end if;

  v_token := gen_random_uuid();
  update library.intake_items i
     set status = 'processing', attempts = i.attempts + 1, claim_token = v_token,
         claimed_at = now(), retry_at = null, error_code = null
   where i.id = p_item;

  return query select 'claimed'::text, v_token, v_item.attempts + 1, v_item.cover_path,
                      v_item.title_page_path, null::timestamptz;
end;
$$;

create or replace function library.finish_intake_item(p_item uuid, p_claim uuid,
                                                      p_extraction jsonb, p_usage jsonb)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_household uuid;
  v_rows int;
begin
  select i.household_id into v_household from library.intake_items i where i.id = p_item;
  if not found or not library.is_member(v_household) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  update library.intake_items i
     set status = 'ready', extraction = p_extraction, vision_usage = p_usage, claim_token = null
   where i.id = p_item
     and i.status = 'processing'
     and i.claim_token = p_claim;
  get diagnostics v_rows = row_count;
  return v_rows > 0;
end;
$$;

create or replace function library.release_intake_item(p_item uuid, p_claim uuid, p_error text,
                                                       p_retry_at timestamptz, p_usage jsonb)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item library.intake_items%rowtype;
  v_status text;
begin
  select i.* into v_item from library.intake_items i where i.id = p_item for update;
  if not found or not library.is_member(v_item.household_id) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  -- A stale or wrong claim changes nothing.
  if v_item.status <> 'processing' or v_item.claim_token is distinct from p_claim or p_claim is null then
    return v_item.status;
  end if;

  if p_retry_at is not null and v_item.attempts < 3 then
    -- Transient error with attempts left: back off.
    update library.intake_items i
       set status = 'pending', retry_at = p_retry_at, claim_token = null,
           vision_usage = coalesce(p_usage, i.vision_usage)
     where i.id = p_item;
    v_status := 'pending';
  elsif p_retry_at is null and p_error is null then
    -- Misconfigured deployment (401/403/402): not billed, so refund the claim.
    update library.intake_items i
       set status = 'pending', retry_at = null, claim_token = null,
           attempts = greatest(i.attempts - 1, 0),
           vision_usage = coalesce(p_usage, i.vision_usage)
     where i.id = p_item;
    update library.intake_usage u
       set vision_calls = greatest(u.vision_calls - 1, 0)
     where u.household_id = v_item.household_id
       and u.day = (v_item.claimed_at at time zone 'utc')::date;
    v_status := 'pending';
  elsif p_retry_at is not null then
    -- Transient error on the last attempt.
    update library.intake_items i
       set status = 'failed', error_code = 'vision_unavailable', retry_at = null, claim_token = null,
           vision_usage = coalesce(p_usage, i.vision_usage)
     where i.id = p_item;
    v_status := 'failed';
  else
    update library.intake_items i
       set status = 'failed', error_code = p_error, retry_at = null, claim_token = null,
           vision_usage = coalesce(p_usage, i.vision_usage)
     where i.id = p_item;
    v_status := 'failed';
  end if;

  return v_status;
end;
$$;

create or replace function library.retry_intake_item(p_item uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_household uuid;
  v_rows int;
begin
  select i.household_id into v_household from library.intake_items i where i.id = p_item;
  if not found or not library.is_member(v_household) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  update library.intake_items i
     set status = 'pending', error_code = null, retry_at = null
   where i.id = p_item
     and i.status = 'failed'
     and i.attempts < 3;
  get diagnostics v_rows = row_count;
  return v_rows > 0;
end;
$$;

create or replace function library.discard_intake_item(p_item uuid, p_reason text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item library.intake_items%rowtype;
begin
  select i.* into v_item from library.intake_items i where i.id = p_item for update;
  if not found or not library.is_member(v_item.household_id) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  if v_item.status = 'discarded' then
    return true;
  end if;
  if v_item.status not in ('pending', 'ready', 'failed') then
    return false;
  end if;

  update library.intake_items i
     set status = 'discarded', discard_reason = p_reason, retry_at = null
   where i.id = p_item;
  return true;
end;
$$;

create or replace function library.confirm_intake_item(p_item uuid, p_book_id uuid,
                                                       p_book jsonb, p_copy jsonb)
returns table (book_id uuid, copy_id uuid)
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_item  library.intake_items%rowtype;
  v_book  uuid;
  v_copy  uuid;
  v_title text;
  v_copy_in jsonb := coalesce(p_copy, '{}'::jsonb);
begin
  select i.* into v_item from library.intake_items i where i.id = p_item for update;
  if not found or not library.is_member(v_item.household_id) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  -- Idempotent: a confirmed item returns its stored result and writes nothing.
  if v_item.status = 'confirmed' then
    return query select v_item.result_book_id, v_item.result_copy_id;
    return;
  end if;

  if v_item.status not in ('ready', 'failed') then
    raise exception 'not_confirmable';
  end if;

  if p_book_id is null then
    v_title := btrim(p_book ->> 'title');
    if v_title is null or v_title = '' then
      raise exception 'title_required' using errcode = '22023';
    end if;

    insert into library.books (household_id, title, authors, synopsis, cover_url, isbn13, isbn10,
                               openlibrary_id, google_books_id, page_count, publisher, publish_date)
    values (
      v_item.household_id,
      v_title,
      array(select e.value from jsonb_array_elements_text(
              case when jsonb_typeof(p_book -> 'authors') = 'array' then p_book -> 'authors' else '[]' end)
              with ordinality e(value, ord) order by e.ord),
      p_book ->> 'synopsis',
      p_book ->> 'cover_url',
      array(select e.value from jsonb_array_elements_text(
              case when jsonb_typeof(p_book -> 'isbn13') = 'array' then p_book -> 'isbn13' else '[]' end)
              with ordinality e(value, ord) order by e.ord),
      array(select e.value from jsonb_array_elements_text(
              case when jsonb_typeof(p_book -> 'isbn10') = 'array' then p_book -> 'isbn10' else '[]' end)
              with ordinality e(value, ord) order by e.ord),
      p_book ->> 'openlibrary_id',
      p_book ->> 'google_books_id',
      (p_book ->> 'page_count')::int,
      p_book ->> 'publisher',
      p_book ->> 'publish_date'
    )
    returning id into v_book;
  else
    select b.id into v_book
      from library.books b
     where b.id = p_book_id
       and b.household_id = v_item.household_id;
    if v_book is null then
      raise exception 'not_authorized' using errcode = '42501';
    end if;
  end if;

  insert into library.copies (book_id, owner_user_id, edition_note, location, origin,
                              photo_path, intake_item_id)
  values (
    v_book,
    -- An absent key keeps the item's owner; an explicit null means shared.
    case when v_copy_in ? 'owner_user_id' then (v_copy_in ->> 'owner_user_id')::uuid
         else v_item.owner_user_id end,
    v_copy_in ->> 'edition_note',
    v_copy_in ->> 'location',
    'photo',
    v_item.cover_path,
    p_item
  )
  returning id into v_copy;

  update library.intake_items i
     set status = 'confirmed', result_book_id = v_book, result_copy_id = v_copy,
         claim_token = null, retry_at = null
   where i.id = p_item;

  return query select v_book, v_copy;
end;
$$;

-- Paths the browser should remove through the Storage API, then pass to
-- mark_intake_purged.
create or replace function library.intake_purgeable(p_household uuid)
returns table (path text)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not library.is_member(p_household) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  return query
    -- Discarded: both photos.
    select i.cover_path
      from library.intake_items i
     where i.household_id = p_household and i.status = 'discarded' and i.cover_path is not null
    union all
    select i.title_page_path
      from library.intake_items i
     where i.household_id = p_household and i.status in ('discarded', 'confirmed')
       and i.title_page_path is not null
    union all
    -- Confirmed: the cover only once no copy keeps it as its photo.
    select i.cover_path
      from library.intake_items i
      left join library.copies c on c.id = i.result_copy_id
     where i.household_id = p_household and i.status = 'confirmed' and i.cover_path is not null
       and (i.result_copy_id is null or c.photo_path is distinct from i.cover_path)
    union all
    -- Upload orphans: objects older than 24 hours whose folder has no item.
    select o.name
      from storage.objects o
     where o.bucket_id = 'library-intake'
       and starts_with(o.name, p_household::text || '/')
       and o.created_at < now() - interval '24 hours'
       and not exists (
         select 1 from library.intake_items i
          where i.household_id = p_household
            and i.id::text = (storage.foldername(o.name))[2]
       );
end;
$$;

-- Nulls the given paths on the household's items, but only where
-- intake_purgeable would list them. Returns the number of path columns nulled.
create or replace function library.mark_intake_purged(p_household uuid, p_paths text[])
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count int;
begin
  if not library.is_member(p_household) then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  with targets as (
    select i.id,
           (i.cover_path = any (p_paths)
            and (i.status = 'discarded'
                 or (i.status = 'confirmed'
                     and (i.result_copy_id is null or c.photo_path is distinct from i.cover_path))))
             as drop_cover,
           (i.title_page_path = any (p_paths) and i.status in ('discarded', 'confirmed'))
             as drop_title
      from library.intake_items i
      left join library.copies c on c.id = i.result_copy_id
     where i.household_id = p_household
       and (i.cover_path = any (p_paths) or i.title_page_path = any (p_paths))
  ),
  updated as (
    update library.intake_items i
       set cover_path      = case when t.drop_cover then null else i.cover_path end,
           title_page_path = case when t.drop_title then null else i.title_page_path end
      from targets t
     where i.id = t.id and (t.drop_cover or t.drop_title)
    returning t.drop_cover::int + t.drop_title::int as n
  )
  select coalesce(sum(n), 0)::int into v_count from updated;

  return v_count;
end;
$$;

