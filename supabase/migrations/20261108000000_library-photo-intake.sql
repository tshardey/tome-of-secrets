-- Library photo intake: photos of book covers (and optional title pages) are
-- uploaded to the private library-intake bucket, read by the library-intake
-- Edge Function, and confirmed by a person into books and copies.
--
-- The Edge Function uses the caller's RLS-scoped client, never an elevated
-- key, so every state change below goes through a security definer RPC that
-- checks library.is_member itself. A missing item raises the same 42501 as a
-- foreign one, so ids can't be probed.
--
-- claim_token is never readable by a client (no select grant on that column):
-- the function learns it only from claim_intake_item's return value. With a
-- readable token a member could refund attempts and daily calls the function
-- had already been billed for.
--
-- Limits: 3 attempts per item (check constraint), 500 vision calls per
-- household per UTC day, 7-minute lease.
--
-- Idempotent: safe to re-run.

---------------------------------------------------------------------------
-- Tables
---------------------------------------------------------------------------

create table if not exists library.intake_items (
  id              uuid primary key, -- generated by the client; part of the photo path
  household_id    uuid not null references library.households (id) on delete cascade,
  uploaded_by     uuid default auth.uid() references auth.users (id) on delete set null,
  batch_id        uuid not null,
  owner_user_id   uuid references auth.users (id) on delete set null, -- null = shared
  cover_path      text, -- null only after purge
  title_page_path text,
  source_hash     text not null check (source_hash ~ '^[0-9a-f]{64}$'),
  status          text not null default 'pending'
                  check (status in ('pending', 'processing', 'ready', 'failed', 'confirmed', 'discarded')),
  attempts        int not null default 0 check (attempts between 0 and 3),
  claim_token     uuid,
  claimed_at      timestamptz,
  retry_at        timestamptz,
  extraction      jsonb,
  vision_usage    jsonb,
  lookup          jsonb,
  error_code      text check (error_code in ('photo_missing', 'vision_refused', 'vision_rejected',
                                             'vision_unreadable', 'vision_unavailable',
                                             'attempts_exhausted')),
  discard_reason  text check (discard_reason in ('discarded', 'already_recorded')),
  result_book_id  uuid references library.books (id) on delete set null,
  result_copy_id  uuid references library.copies (id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint intake_items_cover_required
    check (cover_path is not null or status in ('confirmed', 'discarded')),
  constraint intake_items_cover_path_prefix
    check (cover_path is null
           or starts_with(cover_path, household_id::text || '/' || id::text || '/')),
  constraint intake_items_title_page_path_prefix
    check (title_page_path is null
           or starts_with(title_page_path, household_id::text || '/' || id::text || '/'))
);

-- The same photo can't be open twice in one household (discarded rows don't count).
create unique index if not exists intake_items_source_hash_uq
  on library.intake_items (household_id, source_hash) where status <> 'discarded';
create index if not exists intake_items_household_status_idx
  on library.intake_items (household_id, status);
-- Support the ON DELETE SET NULL actions.
create index if not exists intake_items_uploaded_by_idx
  on library.intake_items (uploaded_by) where uploaded_by is not null;
create index if not exists intake_items_owner_user_id_idx
  on library.intake_items (owner_user_id) where owner_user_id is not null;
create index if not exists intake_items_result_book_id_idx
  on library.intake_items (result_book_id) where result_book_id is not null;
create index if not exists intake_items_result_copy_id_idx
  on library.intake_items (result_copy_id) where result_copy_id is not null;

drop trigger if exists intake_items_set_updated_at on library.intake_items;
create trigger intake_items_set_updated_at
  before update on library.intake_items
  for each row execute function library.set_updated_at();

create table if not exists library.intake_usage (
  household_id uuid not null references library.households (id) on delete cascade,
  day          date not null,
  vision_calls int  not null default 0,
  primary key (household_id, day)
);

-- One copy per intake item, even if the confirm RPC is bypassed.
alter table library.copies add column if not exists
  intake_item_id uuid unique references library.intake_items (id) on delete set null;

